"""
FORAY — fill every demo student's every subject.

    python demo/seed_crosscourse.py        (run AFTER seed_profiles.py)

WHY THIS EXISTS
---------------
S8 enrolled all 8 demo students in all 6 classes, but the seeded records
never caught up: each student had data for ONE subject only. Switching
subject therefore gave a grey constellation and an empty Compass — the
enrolment was real, the story behind it was not.

This script fills every (student, subject) pair that has no data, with
reflections, diagnoses, mastery and per-subject clusters.

DETERMINISTIC. ZERO API CALLS. Every line of text below is hand-authored
or assembled from the taxonomy's own signal phrases, so the seed is
reproducible and rule 8 holds.

THE TWO THINGS THIS MUST NOT BREAK
----------------------------------
1. `M12` is NEVER emitted. Beat 4's 23 -> 4 is recounted LIVE by
   core/efficacy.count_misconception at demo time, so a single extra M12
   diagnosis in week 6 or 7 would move the crown-jewel number.
2. CN cluster rows are NEVER written. Beat 3 reads the clusters table,
   which seed_generator owns. This script only writes clusters for the
   five Semester VI courses.

Both are asserted at the end. The script exits non-zero if either drifted,
so a mistake here fails at seed time rather than on stage.

WHAT EACH SUBJECT GETS
----------------------
Every Semester VI subject gets its own small version of the CN story: one
signature misconception held by 5 of 8 students (k=5, so it surfaces) and
a second held by 2 (below k, so the gate hides it). That means a faculty
member switching subject sees a real heatmap with a real gate, not an
empty grid.
"""

