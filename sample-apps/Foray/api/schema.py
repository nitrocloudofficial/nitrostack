from typing import Literal, Optional, TypedDict

# ═════════════════════════════════════════════════════════════════════
#  CONSTANTS — the deterministic gates. Not configurable at runtime.
# ═════════════════════════════════════════════════════════════════════

K_ANONYMITY = 5
"""R-04. No misconception is surfaced to faculty below this many students.
A safety gate must be deterministic. An LLM gate is not a gate."""

MASTERY_ALPHA = 0.4
"""EMA smoothing for MasteryState.level. Deterministic, explainable on stage."""

COHORT_SIZE = 60
"""Seeded cohort. Beat 3 is '23 of 60'."""


# ═════════════════════════════════════════════════════════════════════
#  STATIC — authored by hand in S1. Never generated by a model.
# ═════════════════════════════════════════════════════════════════════

class Concept(TypedDict):
    id: str                      # "C07" — stable, short
    name: str                    # "Pointer arithmetic"
    unit: str                    # "U1"
    prereqs: list[str]           # concept ids
    x: int                       # HAND-POSITIONED for the SVG.
    y: int                       # Not computed. Not force-directed.


class Misconception(TypedDict):
    id: str                      # "M12"
    concept_id: str              # "C07"
    name: str                    # "Treats pointer increment as +1 byte"
    signals: list[str]           # hints for the classifier, in student language
    correction_hint: str         # "increment scales by sizeof(type)"


class MaterialChunk(TypedDict):
    id: str                      # "MAT_041"
    source: str                  # "Unit1_Notes.pdf"
    page: int                    # 14 — the PRINTED page. Beat 1 cites this.
    text: str
    concept_ids: list[str]       # HAND-TAGGED. This is why we need no vector DB.


# ═════════════════════════════════════════════════════════════════════
#  DYNAMIC — generated at runtime
# ═════════════════════════════════════════════════════════════════════

class Reflection(TypedDict):
    id: str                      # "R_0921"
    student_id: str              # "S_014" — pseudonymous ALWAYS
    concept_ids: list[str]
    week: int
    lang: Literal["en", "ta", "mixed"]
    text: str                    # RAW — permission-gated, see PERMISSIONS below
    created_at: str              # ISO-8601
    # NO score field. NO grade field. Deliberate, and it is R-06.


class Diagnosis(TypedDict):
    id: str                      # "D_0921"
    reflection_id: str
    misconception_ids: list[str]    # from the taxonomy, or []
    novel_text: Optional[str]       # only if nothing matched
    confidence: float
    evidence_span: str              # QUOTED verbatim from the student


class Correction(TypedDict):
    id: str                      # "K_0921"
    diagnosis_id: str
    grounded: bool               # R-02 GATE
    material_ids: list[str]      # REQUIRED non-empty when grounded is True
    text: str
    retrieval_question: str      # one question to check it landed
    status: Literal["sent", "escalated_to_faculty"]


class MasteryHistoryPoint(TypedDict):
    week: int
    level: float


class MasteryState(TypedDict):
    student_id: str
    concept_id: str
    level: float                 # 0.0–1.0, EMA
    last_seen_week: int
    history: list[MasteryHistoryPoint]
    corrected_misconceptions: list[str]   # the "got it wrong then right" trail


class Cluster(TypedDict):
    id: str                      # "CL_006_M12"
    week: int
    misconception_id: str
    student_count: int
    cohort_size: int
    k_satisfied: bool            # R-04 GATE — if False, DO NOT SURFACE
    root_cause_concept_id: str   # traced backwards through prereqs
    root_cause_reasoning: str


class Efficacy(TypedDict):
    checked_week: int
    before_count: int
    after_count: int
    cleared: bool


class Intervention(TypedDict):
    id: str                      # "INT_003"
    cluster_id: str
    kind: Literal["reteach", "worked_example", "problem_set"]
    content: str
    delivered_week: int
    efficacy: Optional[Efficacy]     # deterministic, filled at week+1


class CompassItem(TypedDict):        # R-09
    student_id: str
    gap_concept_id: str
    evidence_reflection_ids: list[str]   # WHY this is on your roadmap
    why: str
    action: str
    priority: int


class AccessLog(TypedDict):          # R-03 — the beat-6 artifact
    actor_role: str
    attempted: str               # "read_raw_reflection:R_0921"
    decision: Literal["ALLOWED", "DENIED"]
    rule: str                    # "P-03: faculty role cannot access raw reflection text"
    req_id: str                  # "R-03"
    ts: str                      # ISO-8601


# ═════════════════════════════════════════════════════════════════════
#  S7 EXTENSION — accounts, classes, chat, questioned topics.
#
#  The original records above are UNCHANGED. This section was added as a
#  deliberate, all-hands schema change (user-directed, post-freeze): real
#  logins, an enrolled class per student, a chat/voice capture surface
#  with an append-only interaction log, and a deterministic count of the
#  topics students actually ask about.
# ═════════════════════════════════════════════════════════════════════

class ClassRoom(TypedDict):
    id: str                      # "CLS_CN5"
    name: str                    # "Computer Networks — Semester V"
    code: str                    # "CS3591"
    unit: str                    # "Transport Layer (Kurose & Ross 8e Ch. 3)"
    faculty_user_id: str         # the ONE teacher
    source: str                  # "sem V.zip / Computer Networks"


class UserAccount(TypedDict):
    id: str                      # "U_001"
    email: str
    name: str
    role: Literal["student", "faculty"]
    password_hash: str           # sha256(salt + password); salt derived from email
    student_id: Optional[str]    # S_xxx — the pseudonymous cohort id
    class_id: Optional[str]      # enrolment (students) / taught class (faculty)
    scenario: Optional[str]      # roster label, e.g. "Cleared after intervention"
    scenario_note: Optional[str] # one-line case summary shown to faculty


class ChatSession(TypedDict):
    id: str                      # "CS_0001"
    student_id: str
    class_id: str
    started_at: str              # ISO-8601
    ended_at: Optional[str]
    misconception_ids: list[str]     # named during this session
    question_concept_ids: list[str]  # topics the student questioned


class ChatMessage(TypedDict):        # APPEND-ONLY. The regulation log.
    id: int
    session_id: str
    student_id: str
    sender: Literal["student", "agent"]
    text: str
    analysis: Optional[dict]     # what the pipeline found for THIS message
    ts: str


class TopicQuestion(TypedDict):      # R-12 — counted, never generated
    id: int
    student_id: str
    class_id: str
    concept_id: str
    week: int
    source: Literal["chat", "seed"]
    excerpt: str                 # the question as asked, for the record
    ts: str


# ═════════════════════════════════════════════════════════════════════
#  THE PERMISSIONS MATRIX — foray_plan.md §6.3
#
#  This table IS the architecture. The Warden reads it; it is not a
#  policy document, it is the enforcement point. Beat 6 depends on it.
#
#  Scopes:
#    course_content    the prescribed textbook. Not student data, so every
#                      role reads it (§3.1). The Grounding Verifier cannot
#                      satisfy R-02 without it.
#    raw_reflection    the student's own words, unredacted
#    individual_mastery  one named student's MasteryState
#    cohort_aggregate  counts and clusters only — never raw text
#    multi_cohort      across cohorts / years
# ═════════════════════════════════════════════════════════════════════

Scope = Literal[
    "course_content",
    "raw_reflection",
    "individual_mastery",
    "cohort_aggregate",
    "multi_cohort",
    # ── S7 ──
    "student_profile",   # roster summaries: names, scenarios, COUNTS. No raw text.
    "chat_log",          # raw chat transcripts — the regulation log
]

Role = Literal[
    "elicitor",
    "diagnostician",
    "grounding_verifier",
    "mastery_updater",
    "root_cause_analyst",
    "intervention_designer",
    "compass",
    "student",
    "faculty",
]

_CONTENT = {"course_content"}          # every role reads prescribed material

PERMISSIONS: dict[Role, set[Scope]] = {
    # ── Loop 1 agents: see the words, never the cohort ──
    # The Elicitor and Diagnostician also hold chat_log: the Elicitor IS the
    # conversation, and the Diagnostician analyses it turn by turn.
    "elicitor":              _CONTENT | {"raw_reflection", "chat_log"},
    "diagnostician":         _CONTENT | {"raw_reflection", "chat_log"},
    "grounding_verifier":    _CONTENT | {"raw_reflection"},
    "mastery_updater":       _CONTENT | {"individual_mastery"},
    # ── Loop 2 agents: see the cohort, structurally never the words ──
    "root_cause_analyst":    _CONTENT | {"cohort_aggregate"},
    "intervention_designer": _CONTENT | {"cohort_aggregate"},
    # ── Loop 3 ──
    "compass":               _CONTENT | {"individual_mastery"},  # own student
    # ── Humans ──
    "student":               _CONTENT | {"raw_reflection", "individual_mastery",
                                         "chat_log"},   # their OWN transcript
    "faculty":               _CONTENT | {"cohort_aggregate", "multi_cohort",
                                         "student_profile"},
    #                          ^ NOTE what is absent: raw_reflection,
    #                            individual_mastery and chat_log. Faculty sees
    #                            the roster and the counts — never the words.
    #                            That absence is beat 6.
}

DENIAL_RULES: dict[tuple[str, str], tuple[str, str]] = {
    # (role, scope) -> (rule_id_and_text, req_id)
    ("faculty", "raw_reflection"): (
        "P-03: faculty role cannot access raw reflection text",
        "R-03",
    ),
    ("faculty", "individual_mastery"): (
        "P-04: faculty role cannot access an individual student's mastery",
        "R-03",
    ),
    ("root_cause_analyst", "raw_reflection"): (
        "P-05: cohort agents are never given raw student text",
        "R-03",
    ),
    ("intervention_designer", "raw_reflection"): (
        "P-05: cohort agents are never given raw student text",
        "R-03",
    ),
    ("faculty", "chat_log"): (
        "P-06: faculty role cannot read raw chat transcripts",
        "R-11",
    ),
}


def denial_reason(role: str, scope: str) -> tuple[str, str]:
    """Rule text + requirement id for an access denial. Used by the Warden
    to populate AccessLog. Falls back to a generic rule for unlisted pairs."""
    return DENIAL_RULES.get(
        (role, scope),
        (f"P-00: role '{role}' has no grant for scope '{scope}'", "R-03"),
    )


