#!/usr/bin/env node
/**
 * gen-earth-mask.mjs — bake the dotted-globe land bitmap.
 *
 * The login page and the landing hero render a rotating, orthographically
 * projected dot-matrix Earth (the "earth UI"). Doing point-in-polygon tests
 * against real coastline GeoJSON at 60fps in the browser is absurd, so this
 * script does the geometry ONCE at authoring time and bakes the result into
 * `src/modules/console/earth-mask.ts` as a base64 bit-grid:
 *
 *   width  = 240 samples of longitude  (-180..180)
 *   height = 120 samples of latitude   ( 85..-85, Mercator-ish crop)
 *   bit(x,y) = 1 when the sample point is on land
 *
 * Run it only when you want to regenerate the mask:
 *   node scripts/gen-earth-mask.mjs
 *
 * It needs network access (fetches Natural Earth 110m land polygons from the
 * world-atlas mirror). The generated file is committed, so CI and deploys never
 * run this.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC =
  'https://raw.githubusercontent.com/johan/world.geo.json/master/countries.geo.json';
const W = 240;
const H = 120;
const LAT_MAX = 85;

function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const intersects =
      yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}

function pointInPolygon(lon, lat, polygon) {
  // polygon = [outerRing, ...holes]
  if (!pointInRing(lon, lat, polygon[0])) return false;
  for (let h = 1; h < polygon.length; h++) {
    if (pointInRing(lon, lat, polygon[h])) return false;
  }
  return true;
}

const res = await fetch(SRC);
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const geo = await res.json();

const polygons = [];
const boxes = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (!g) continue;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const p of polys) {
    polygons.push(p);
    let minX = 180, maxX = -180, minY = 90, maxY = -90;
    for (const [x, y] of p[0]) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    boxes.push([minX, minY, maxX, maxY]);
  }
}

const bits = new Uint8Array(Math.ceil((W * H) / 8));
let landCount = 0;
for (let y = 0; y < H; y++) {
  const lat = LAT_MAX - ((y + 0.5) / H) * (LAT_MAX * 2);
  for (let x = 0; x < W; x++) {
    const lon = -180 + ((x + 0.5) / W) * 360;
    let land = false;
    for (let i = 0; i < polygons.length && !land; i++) {
      const [minX, minY, maxX, maxY] = boxes[i];
      if (lon < minX || lon > maxX || lat < minY || lat > maxY) continue;
      land = pointInPolygon(lon, lat, polygons[i]);
    }
    if (land) {
      const idx = y * W + x;
      bits[idx >> 3] |= 1 << (idx & 7);
      landCount++;
    }
  }
}

const b64 = Buffer.from(bits).toString('base64');
const out = `/**
 * earth-mask.ts — GENERATED by scripts/gen-earth-mask.mjs. Do not hand-edit.
 *
 * A ${W}x${H} bit-grid of Earth's landmass (equirectangular, lat +${LAT_MAX}..-${LAT_MAX}),
 * base64-encoded, ${landCount} land samples. Consumed by the dotted-globe canvas
 * on the login page and the landing hero.
 */
export const EARTH_MASK_W = ${W};
export const EARTH_MASK_H = ${H};
export const EARTH_MASK_LAT_MAX = ${LAT_MAX};
export const EARTH_MASK_B64 =
  '${b64.replace(/(.{76})/g, "$1' +\n  '")}';
`;

const dest = join(process.cwd(), 'src', 'modules', 'console', 'earth-mask.ts');
writeFileSync(dest, out);
console.log(`wrote ${dest} — ${landCount}/${W * H} land samples, ${b64.length} b64 chars`);
