let nextStudentId = 26;
let nextTeamId = 2;

export function addStudent(studentData) {
  const expLevel = studentData.experience_level || studentData.experience || "intermediate";
  const newStudent = {
    id: nextStudentId++,
    name: studentData.name,
    department: studentData.department || "Computer Science",
    year: studentData.year || "3rd Year",
    skills: Array.isArray(studentData.skills) ? studentData.skills : [],
    interests: Array.isArray(studentData.interests) ? studentData.interests : [],
    experience_level: expLevel,
    availability: Array.isArray(studentData.availability) && studentData.availability.length > 0 ? studentData.availability : ["weekends"],
    isRegistered: true,
    registeredAt: new Date().toISOString()
  };
  db.students.unshift(newStudent); // Put newly registered student at top of roster!
  return newStudent;
}

export function createTeam(projectName, memberIds, projectType = "general") {
  const newTeam = {
    id: nextTeamId++,
    project_name: projectName,
    project_type: projectType,
    member_ids: memberIds,
    status: "active"
  };
  db.teams.push(newTeam);
  return newTeam;
}

