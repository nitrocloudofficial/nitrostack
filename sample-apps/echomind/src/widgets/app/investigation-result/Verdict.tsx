"use client";

import { motion } from "framer-motion";
import {
  BrainCircuit,
  ShieldCheck,
  TriangleAlert,
  Lightbulb,
  CheckCircle2,
} from "lucide-react";
import { useWidgetSDK } from "@nitrostack/widgets";

import { colors } from "./styles";

interface VerdictData {
  summary: string;
  rootCause: string;
  recommendation: string;
  confidence: number;
}

interface Props {
  verdict: VerdictData;
  card: string;
  secondary: string;
  isDark: boolean;
}

export default function Verdict({
  verdict,
  card,
  secondary,
  isDark,
}: Props) {
  const { sendFollowUpMessage, isReady } = useWidgetSDK();

  // Defensive: ensure verdict fields exist
  const safeVerdict = {
    summary: verdict?.summary ?? "(No summary available)",
    rootCause: verdict?.rootCause ?? "(No root cause identified)",
    recommendation: verdict?.recommendation ?? "(No recommendation available)",
    confidence: verdict?.confidence ?? 0,
  };

  const sections = [
    {
      title: "Summary",
      icon: BrainCircuit,
      color: "#3B82F6",
      text: safeVerdict.summary,
    },
    {
      title: "Root Cause",
      icon: TriangleAlert,
      color: "#F59E0B",
      text: safeVerdict.rootCause,
    },
    {
      title: "Recommendation",
      icon: Lightbulb,
      color: "#10B981", // Vibrant emerald green
      text: safeVerdict.recommendation,
    },
  ];

  const handleSectionClick = (title: string) => {
    if (isReady) {
      sendFollowUpMessage(`Elaborate further on the ${title} for this investigation.`);
    }
  };

  const handleConfidenceClick = () => {
    if (isReady) {
      sendFollowUpMessage(`Explain how the ${safeVerdict.confidence}% AI confidence score was calculated.`);
    }
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 25 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.45 }}
      style={{
        background: colors.surface,
        backdropFilter: "blur(24px)",
        WebkitBackdropFilter: "blur(24px)",
        borderRadius: 24,
        padding: 30,
        marginTop: 30,
        border: `1px solid ${colors.border}`,
        boxShadow: "0 20px 50px rgba(0, 0, 0, 0.6)",
      }}
    >
      {/* Header */}

      <div
        style={{
          display: "flex",
          justifyContent: "space-between",
          alignItems: "center",
          marginBottom: 28,
        }}
      >
        <motion.div
          initial={{ opacity: 0, x: -20 }}
          animate={{ opacity: 1, x: 0 }}
          transition={{ delay: 0.1 }}
        >
          <h2
            style={{
              margin: 0,
              fontSize: 28,
              fontWeight: 800,
              background: "linear-gradient(135deg, #3B82F6, #8B5CF6)",
              WebkitBackgroundClip: "text",
              WebkitTextFillColor: "transparent",
              backgroundClip: "text",
              textShadow: "0 0 30px rgba(59, 130, 246, 0.2)",
            }}
          >
            AI Investigation Report
          </h2>

          <div
            style={{
              marginTop: 6,
              color: secondary,
              fontSize: 14,
              fontWeight: 500,
            }}
          >
            Generated by EchoMind AI
          </div>
        </motion.div>

        <motion.div
          whileHover={{ scale: 1.1 }}
          style={{
            width: 72,
            height: 72,
            borderRadius: 20,
            background:
              "linear-gradient(135deg, #3B82F6, #8B5CF6)",
            display: "flex",
            justifyContent: "center",
            alignItems: "center",
            boxShadow:
              "0 0 35px rgba(59, 130, 246, 0.4)",
          }}
        >
          <BrainCircuit
            size={34}
            color="white"
          />
        </motion.div>
      </div>

      {/* Report Sections */}

      {sections.map((section, index) => {
        const Icon = section.icon;

        return (
          <motion.div
            key={section.title}
            initial={{ opacity: 0, y: 20 }}
            whileInView={{ opacity: 1, y: 0 }}
            viewport={{ once: true }}
            transition={{
              delay: index * 0.12,
            }}
            whileHover={{ scale: 1.01 }}
            onClick={() => handleSectionClick(section.title)}
            style={{
              marginBottom: 24,
              padding: 22,
              borderRadius: 18,
              background: "rgba(255, 255, 255, 0.02)",
              border: `1px solid ${colors.border}`,
              cursor: "pointer",
              transition: "all 0.3s ease",
            }}
          >
            <div
              style={{
                display: "flex",
                alignItems: "center",
                gap: 12,
                marginBottom: 14,
              }}
            >
              <motion.div
                whileHover={{ rotate: 10 }}
                style={{
                  width: 42,
                  height: 42,
                  borderRadius: 14,
                  background: `${section.color}22`,
                  color: section.color,
                  display: "flex",
                  justifyContent: "center",
                  alignItems: "center",
                  boxShadow: `0 0 15px ${section.color}33`,
                }}
              >
                <Icon size={22} />
              </motion.div>

              <div
                style={{
                  fontSize: 18,
                  fontWeight: 700,
                  color: colors.text,
                }}
              >
                {section.title}
              </div>
            </div>

            <div
              style={{
                lineHeight: 1.8,
                color: colors.secondary,
                fontSize: 15,
                fontStyle: section.text.startsWith("(") ? "italic" : "normal",
                wordWrap: "break-word",
                whiteSpace: "normal",
                overflowWrap: "break-word",
                maxWidth: "100%",
              }}
            >
              {section.text}
            </div>
          </motion.div>
        );
      })}

      {/* Confidence Card */}

      <motion.div
        whileHover={{ scale: 1.02 }}
        initial={{ opacity: 0, y: 20 }}
        whileInView={{ opacity: 1, y: 0 }}
        viewport={{ once: true }}
        transition={{ delay: 0.4 }}
        onClick={handleConfidenceClick}
        style={{
          marginTop: 10,
          borderRadius: 20,
          padding: 24,
          background: "linear-gradient(135deg, rgba(59, 130, 246, 0.1), rgba(139, 92, 246, 0.05))",
          border: "1px solid rgba(59, 130, 246, 0.2)",
          boxShadow: "0 0 30px rgba(59, 130, 246, 0.1)",
          cursor: "pointer",
        }}
      >
        <div
          style={{
            display: "flex",
            justifyContent: "space-between",
            alignItems: "center",
          }}
        >
          <div>
            <div
              style={{
                opacity: 0.85,
                fontSize: 14,
                color: colors.secondary,
                fontWeight: 500,
              }}
            >
              AI Confidence Score
            </div>

            <motion.div
              initial={{ scale: 0.5 }}
              whileInView={{ scale: 1 }}
              viewport={{ once: true }}
              transition={{ delay: 0.5, type: "spring" }}
              style={{
                marginTop: 8,
                fontSize: 42,
                fontWeight: 800,
                background: "linear-gradient(135deg, #3B82F6, #10B981)",
                WebkitBackgroundClip: "text",
                WebkitTextFillColor: "transparent",
                backgroundClip: "text",
              }}
            >
              {safeVerdict.confidence}%
            </motion.div>
          </div>

          <motion.div
            animate={{ rotate: 360 }}
            transition={{ duration: 20, repeat: Infinity, ease: "linear" }}
          >
            <ShieldCheck
              size={54}
              color="#10B981"
            />
          </motion.div>
        </div>

        <div
          style={{
            marginTop: 18,
            height: 8,
            borderRadius: 999,
            background: "rgba(255, 255, 255, 0.05)",
            overflow: "hidden",
            border: "1px solid rgba(59, 130, 246, 0.1)",
          }}
        >
          <motion.div
            initial={{ width: 0 }}
            whileInView={{ width: `${safeVerdict.confidence}%` }}
            viewport={{ once: true }}
            transition={{
              duration: 1.2,
              ease: "easeOut",
            }}
            style={{
              height: "100%",
              background: "linear-gradient(90deg, #10B981, #059669)",
              boxShadow: "0 0 15px rgba(16, 185, 129, 0.5)",
            }}
          />
        </div>

        <div
          style={{
            marginTop: 16,
            fontSize: 14,
            opacity: 0.9,
            color: colors.text,
            fontWeight: 500,
          }}
        >
          Investigation successfully completed with high confidence.
        </div>
      </motion.div>

      {/* Completion Footer */}

      <motion.div
        initial={{ opacity: 0 }}
        whileInView={{ opacity: 1 }}
        viewport={{ once: true }}
        transition={{ delay: 0.3 }}
        style={{
          marginTop: 40,
          paddingTop: 28,
          borderTop: `1px solid ${colors.border}`,
          textAlign: "center",
        }}
      >
        <motion.div
          animate={{ scale: [1, 1.1, 1] }}
          transition={{ duration: 2, repeat: Infinity }}
        >
          <CheckCircle2
            size={42}
            color="#10B981"
          />
        </motion.div>

        <div
          style={{
            marginTop: 14,
            fontSize: 22,
            fontWeight: 800,
            color: colors.text,
          }}
        >
          Investigation Completed Successfully
        </div>

        <div
          style={{
            marginTop: 12,
            color: colors.secondary,
            fontSize: 15,
            lineHeight: 1.7,
            fontWeight: 500,
          }}
        >
          Root cause identified • Timeline reconstructed •
          Evidence correlated • AI recommendation generated
        </div>

        <div
          style={{
            marginTop: 18,
            display: "inline-flex",
            gap: 12,
            flexWrap: "wrap",
            justifyContent: "center",
          }}
        >
          <motion.div
            whileHover={{ scale: 1.05 }}
            onClick={handleConfidenceClick}
            style={{
              background: "rgba(16, 185, 129, 0.1)",
              color: "#10B981",
              padding: "8px 14px",
              borderRadius: 999,
              fontWeight: 600,
              fontSize: 13,
              border: "1px solid rgba(16, 185, 129, 0.2)",
              cursor: "pointer",
            }}
          >
            {safeVerdict.confidence}% Confidence
          </motion.div>

          <motion.div
            whileHover={{ scale: 1.05 }}
            onClick={() => handleSectionClick("Summary")}
            style={{
              background: "rgba(59, 130, 246, 0.1)",
              color: "#3B82F6",
              padding: "8px 14px",
              borderRadius: 999,
              fontWeight: 600,
              fontSize: 13,
              border: "1px solid rgba(59, 130, 246, 0.2)",
              cursor: "pointer",
            }}
          >
            AI Verified
          </motion.div>
        </div>

        <div
          style={{
            marginTop: 20,
            color: colors.secondary,
            fontSize: 13,
            fontWeight: 500,
          }}
        >
          Powered by <strong>EchoMind AI</strong> • Enterprise Engineering
          Memory Platform
        </div>
      </motion.div>
    </motion.div>
  );
}
