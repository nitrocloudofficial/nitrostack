function slice(file, ranges) {
  const full = readFileSync(path.join(root, "src/modules", file), "utf-8").split("\n");
  const parts = ranges.map(([start, end]) => full.slice(start - 1, end).join("\n"));
  return parts.join("\n\n");
}

function sourceRef(file, ranges) {
  return `modules/${file}:${ranges.map(([s, e]) => (s === e ? `${s}` : `${s}-${e}`)).join(",")}`;
}

